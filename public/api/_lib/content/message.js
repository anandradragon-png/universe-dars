// Постобработка текста от AI: чистка иноязычных вкраплений, запрещённых слов,
// нестандартных символов. Страховка — основная защита в промпте.
const russifyText = (s) => {
  if (!s || typeof s !== 'string') return s;
  let out = s
    // Точечные замены частых английских паразитов
    .replace(/\bseemingly\b/gi, 'словно')
    .replace(/\bseems?\b/gi, 'кажется')
    .replace(/\btruly\b/gi, 'поистине')
    .replace(/\breally\b/gi, 'действительно')
    .replace(/\bindeed\b/gi, 'действительно')
    .replace(/\bactually\b/gi, 'на самом деле')
    .replace(/\bperhaps\b/gi, 'возможно')
    .replace(/\bBEGIN\b/gi, '')
    .replace(/\bEND\b/gi, '')
    // Запрещённые слова → бережные синонимы. \b не работает с кириллицей в JS,
    // поэтому границы через look-around по не-буквенным символам.
    .replace(/(^|[^а-яёА-ЯЁ])манипул[а-яё]*/gi, '$1взаимодействовать')
    .replace(/(^|[^а-яёА-ЯЁ])контролир[а-яё]*/gi, '$1осознавать')
    .replace(/(^|[^а-яёА-ЯЁ])подчин(я|и)[а-яё]*/gi, '$1настраивать')
    .replace(/(^|[^а-яёА-ЯЁ])заставля[а-яё]*/gi, '$1приглашать')
    .replace(/(^|[^а-яёА-ЯЁ])принужда[а-яё]*/gi, '$1побуждать')
    // Постпроцессор для штампов из словаря «Матрицы полей» — DeepSeek
    // системно их вставляет, несмотря на явные запреты в промпте.
    // Заменяем после генерации, чтобы юзер их не видел.
    // «окостенение» во всех падежах → «застывание системы» с правильным окончанием
    .replace(/(^|[^а-яёА-ЯЁ])окостенение(\s|$|[,.;:!?])/gi, '$1застывание системы$2')
    .replace(/(^|[^а-яёА-ЯЁ])окостенения(\s|$|[,.;:!?])/gi, '$1застывания системы$2')
    .replace(/(^|[^а-яёА-ЯЁ])окостенению(\s|$|[,.;:!?])/gi, '$1застыванию системы$2')
    .replace(/(^|[^а-яёА-ЯЁ])окостенением(\s|$|[,.;:!?])/gi, '$1застыванием системы$2')
    .replace(/(^|[^а-яёА-ЯЁ])окостенении(\s|$|[,.;:!?])/gi, '$1застывании системы$2')
    .replace(/(^|[^а-яёА-ЯЁ])окостенел[а-яё]*/gi, '$1жёсткий')
    // 01.05.2026: УБРАНА замена «суета → беготня без опоры» — она ломала
    // тексты («организуешь совместный вечер без беготни без опоры»).
    // AI пишет «суету» нормально, не нужно её подменять.
    // Также убрана замена «пустые связи → контакты без глубины» по той же
    // причине: AI и так пишет нормально, подмена ломала контекст.
    // «выбивает (тебя/меня/...)» → «закрывает»
    .replace(/(^|[^а-яёА-ЯЁ])выбивает\s+(тебя|меня|её|его|их)/gi, '$1закрывает $2')
    .replace(/(^|[^а-яёА-ЯЁ])выбивае(шь|т)\s+из\s+(равновесия|колеи|ритма)/gi, '$1сбивае$2 ритм')
    // Замена «нужно/надо/должен»→«важно/стоит» намеренно убрана: автозамена
    // рвёт грамматику («ты должен быть гибким» → «ты важно быть гибким»).
    // За мягкую подачу отвечает промпт.
    // Безопасная косметика: «ты - это X» → «ты - X» (убираем связку «это»,
    // которая превращает живой образ в определение-шаблон).
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s*-\s*это\s+/g, '$1$2ы - ')
    // Согласование «ты» с глаголами: AI иногда пишет формы «Вы» (находитесь,
    // бываете, делаете). Заменяем на правильные формы «ты», сохраняя регистр
    // первой буквы (Т/т).
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+находитесь(?![а-яё])/g, '$1$2ы находишься')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+бываете(?![а-яё])/g, '$1$2ы бываешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+становитесь(?![а-яё])/g, '$1$2ы становишься')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+чувствуете(?![а-яё])/g, '$1$2ы чувствуешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+слышите(?![а-яё])/g, '$1$2ы слышишь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+видите(?![а-яё])/g, '$1$2ы видишь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+знаете(?![а-яё])/g, '$1$2ы знаешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+делаете(?![а-яё])/g, '$1$2ы делаешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+можете(?![а-яё])/g, '$1$2ы можешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+хотите(?![а-яё])/g, '$1$2ы хочешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+идёте(?![а-яё])/g, '$1$2ы идёшь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+живёте(?![а-яё])/g, '$1$2ы живёшь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+умеете(?![а-яё])/g, '$1$2ы умеешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+любите(?![а-яё])/g, '$1$2ы любишь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+слушаете(?![а-яё])/g, '$1$2ы слушаешь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+говорите(?![а-яё])/g, '$1$2ы говоришь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+держите(?![а-яё])/g, '$1$2ы держишь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+приносите(?![а-яё])/g, '$1$2ы приносишь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+создаёте(?![а-яё])/g, '$1$2ы создаёшь')
    .replace(/(^|[^а-яёА-ЯЁ])([Тт])ы\s+ставите(?![а-яё])/g, '$1$2ы ставишь')
    // Чистка иноязычных вкраплений. AI иногда подмешивает латиницу посреди
    // русского слова («buildить целые города») — стрипаем ВСЁ слово целиком,
    // иначе остаётся огрызок «ить». Слово = последовательность не-пробельных
    // не-знаков-препинания символов.
    .replace(/[áéíóúñçßàèìòùâêîôûäëïöüãõøœæ]/giu, '')
    .replace(/(?:^|\s)[^\s.,!?;:«»"'()\-—]*[a-zA-Z][^\s.,!?;:«»"'()\-—]*/g, ' ')
    // CJK (китайский/японский/корейский), арабский, иврит — аналогично
    .replace(/(?:^|\s)[^\s.,!?;:«»"'()\-—]*[\u4E00-\u9FFF\u3040-\u30FF\u3130-\u318F\uAC00-\uD7AF\u3000-\u303F\u0590-\u05FF\u0600-\u06FF][^\s.,!?;:«»"'()\-—]*/g, ' ')
    // Типографика
    .replace(/\u2014/g, '-')
    .replace(/\u2013/g, '-')
    .replace(/\u00A0/g, ' ')
    // Лишние пробелы и пустые скобки
    .replace(/\s+([,.!?;:])/g, '$1')
    .replace(/\(\s*\)/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();

  // Итеративная замена шаблона «ты не просто X, ты — Y» — оставляем первое
  // вхождение (если оно уместно), остальные заменяем на живое обобщение.
  // Цепочка .replace с /g ловит только соседние пары, итерация — все повторы.
  let patternCount = 0;
  out = out.replace(/ты\s+не\s+просто\s+[а-яё]+[,—-]\s+ты\s*[—-]\s*[а-яё]+/gi, (m) => {
    patternCount++;
    return patternCount === 1 ? m : 'и это её собственное';
  });

  // 30.04.2026 — последний защитный пояс. Третье лицо не используем
  // (запутает читателя). Только убираем поломанные/повторяющиеся
  // «Ты Х. Ты Y. Ты Z.» подряд и контейнерные формулы.
  out = out
    // 3 коротких «Ты ___.» подряд → одно перечисление
    .replace(/(^|[.!?]\s+)(Т|т)ы\s+([а-яё]+)\.\s+(Т|т)ы\s+([а-яё]+)\.\s+(Т|т)ы\s+([а-яё]+)\./g,
             '$1$2ы $3, $5 и $7.')
    // 2 коротких «Ты Х. Ты Y.» подряд (если оба — однословные краткие
    // прилагательные, типа «Ты редкая. Ты глубокая.») → склеиваем
    .replace(/(^|[.!?]\s+)(Т|т)ы\s+([а-яё]{4,12})\.\s+(Т|т)ы\s+([а-яё]{4,12})\./g,
             '$1$2ы $3 и $5.')
    // 01.05.2026: контейнерные формулы «в тебе живёт/встретились» снова
    // прорываются через промт. Заменяем на простое «у тебя есть».
    // Это сохраняет смысл и ракурс читателя (никакого 3-го лица).
    .replace(/(^|[^а-яёА-ЯЁ])в\s+тебе\s+живут\b/gi, '$1у тебя есть')
    .replace(/(^|[^а-яёА-ЯЁ])в\s+тебе\s+живёт\b/gi, '$1у тебя есть')
    .replace(/(^|[^а-яёА-ЯЁ])в\s+тебе\s+встретили?сь\b/gi, '$1у тебя соединяются')
    .replace(/(^|[^а-яёА-ЯЁ])в\s+тебе\s+соединили?сь\b/gi, '$1у тебя соединяются')
    // 01.05.2026: УБРАНА regex-замена «Ты редкая/глубокая/тонкая → пусто».
    // Она ломала грамматику: после удаления «Ты редкая» оставались хвосты
    // типа «Ты та редкий человек, который...». Запрет на этот штамп
    // оставлен только в промте — AI его соблюдает.
    // Поэтические штампы, которые вырвались из промта (макс 1 раз должны
    // быть, AI игнорирует). Программно режем избыток.
    .replace(/несущ(ий|ая|ие)\s+каркас(ом|а)?\s+реальност(и|ью)/gi, 'опора')
    .replace(/каркас(ом|а)?\s+реальности/gi, 'опора')
    .replace(/кости\s+ситуации/gi, 'основа ситуации')
    .replace(/скелет\s+ситуации/gi, 'основа ситуации')
    .replace(/скелет\s+(реальности|событий|жизни|мира)/gi, 'основа $1')
    .replace(/основанием\s+позвоночника/gi, 'спиной')
    // 01.05.2026 — запрет шаблонных «комплиментов уникальности»,
    // которые автор отвергла как штампы. Удаляем фразы целиком.
    .replace(/\.?\s*Не\s+каждый\s+умеет\s+так[^.!?]*[.!?]/gi, '.')
    .replace(/\.?\s*Этому\s+невозможно\s+научиться[^.!?]*[.!?]/gi, '.')
    .replace(/\s*и\s+в\s+этом\s+твоя\s+сила/gi, '');

  return out;
};

// Согласование рода: если читатель — женщина, заменяем мужские формы прошедшего
