async function runMessageGeneration({ systemMsg, userPrompt, isFemale, provider, lang }) {
  // Локализация: для ru (или если lang не передан) — systemMsg как есть.
  // Для en/es префиксируется инструкция языка. Сам русский промпт не меняется.
  let finalSystemMsg = systemMsg;
  if (lang && lang !== 'ru') {
    try {
      const language = require('../language');
      finalSystemMsg = language.applyLanguage(systemMsg, lang);
    } catch (e) {
      // language.js не доступен — оставляем как есть (graceful)
    }
  }

  const messages = [
    { role: 'system', content: finalSystemMsg },
    { role: 'user', content: userPrompt }
  ];

  // Forced provider — для Песочницы (явный выбор)
  if (provider === 'groq') {
    return await _runViaGroq(messages, isFemale);
  }
  if (provider === 'deepseek') {
    const completion = await _runViaDeepseek(messages);
    return _parseAndPostprocess(completion, isFemale, lang);
  }

  // Default: DeepSeek с fallback на Groq при сбое
  try {
    const completion = await _runViaDeepseek(messages);
    return _parseAndPostprocess(completion, isFemale, lang);
  } catch (e) {
    console.warn('[message] DeepSeek failed, falling back to Groq:', e.message);
    return await _runViaGroq(messages, isFemale);
  }
}

async function _runViaDeepseek(messages) {
  const ds = require('../deepseek');
  return await ds.chatCompletion({
    messages,
    model: 'deepseek-chat',
    temperature: 0.85,  // 0.95 → 0.85: меньше галлюцинаций, лучше соблюдение JSON
    max_tokens: 5000,
    response_format: { type: 'json_object' }  // гарантия валидного JSON
  });
}

async function _runViaGroq(messages, isFemale) {
  const groq = new Groq({ apiKey: (process.env.GROQ_API_KEY || '').trim() });
  let completion;
  try {
    completion = await groq.chat.completions.create({
      messages,
      model: 'llama-3.3-70b-versatile',
      temperature: 0.6,
      max_tokens: 4500,
      response_format: { type: 'json_object' }
    });
  } catch (modelErr) {
    completion = await groq.chat.completions.create({
      messages,
      model: 'llama-3.1-8b-instant',
      temperature: 0.6,
      max_tokens: 4500,
      response_format: { type: 'json_object' }
    });
  }
  return _parseAndPostprocess(completion, isFemale, lang);
}

function _parseAndPostprocess(completion, isFemale, lang) {
  const raw = completion.choices[0]?.message?.content || '';
  const start = raw.indexOf('{');
  const end   = raw.lastIndexOf('}');
  if (start === -1 || end === -1) throw new Error('JSON не найден в ответе AI');
  const clean = raw.slice(start, end + 1);
  let parsed;
  try { parsed = JSON.parse(clean); }
  catch { throw new Error('Ошибка разбора JSON'); }

  // russifyText вырезает ВСЮ латиницу и чистит под русский — для EN/ES это
  // уничтожает текст. feminizeText — тоже русские формы рода. Применяем
  // постпроцессинг ТОЛЬКО к русской версии.
  const isRu = !lang || lang === 'ru';
  const processString = (str) => {
    if (!isRu) return str;
    let s = russifyText(str);
    if (isFemale) s = feminizeText(s);
    return s;
  };
  const clean_ = (v) => {
    if (typeof v === 'string') return processString(v);
    if (Array.isArray(v)) return v.map(clean_);
    if (v && typeof v === 'object') {
      const out = {};
      for (const k of Object.keys(v)) out[k] = clean_(v[k]);
      return out;
    }
    return v;
  };
  const cleaned = clean_(parsed);

  // Чистим только legacy-поля старой схемы (sacred_energy/light_part/...).
  // traps и key_to_self теперь часть новой схемы (закон 30.04.2026 v2),
  // их удалять нельзя.
  delete cleaned.growth_points;
  delete cleaned.transition_keys;
  delete cleaned.ecology;
  delete cleaned.sacred_energy;
  delete cleaned.light_part;

  // «Феникс» в архетипе — РАЗРЕШЁН по решению Светы 30.04.2026.
  // Запрет был в v5, но Свете нравится «ФЕНИКС ВРЕМЕНИ» как пример.
  // Чистим только markdown-маркеры из девиза.
  if (cleaned.archetype && typeof cleaned.archetype === 'object') {
    if (cleaned.archetype.motto) {
      cleaned.archetype.motto = String(cleaned.archetype.motto)
        .replace(/^["'«»_*`]+|["'«»_*`]+$/g, '')
        .trim();
    }
    // 01.05.2026: «Зодчий» автор просила исключить из архетипов как редкое
    // непонятное слово. AI всё равно его выдаёт — фильтруем программно.
    if (cleaned.archetype.title) {
      cleaned.archetype.title = String(cleaned.archetype.title)
        .replace(/\bЗОДЧИЙ\b/gi, 'ТКАЧ')
        .replace(/\bЗОДЧАЯ\b/gi, 'ТКАЧ')
        .trim();
    }
  }

  return cleaned;
}

