function lower(s) { return s ? s.charAt(0).toLowerCase() + s.slice(1) : s; }

// Суть дня. Первая строка идёт в превью уведомления, поэтому она должна быть
// верна характеру самого Дара: ведём от его метафоры (без сырого эзотеричного
// текста энциклопедии) + чистая тема дня по КУН-полю (как проявляется вовне).
// Для 17 интеграторов метафоры нет — берём тему их поля в полную силу.
function buildIntro(code, ma, zhi, kun) {
  const ext = EXT[code];
  if (ext && ext.metaphor) {
    return `Сегодня в силе ${lower(ext.metaphor.trim())} — ${KUN_THEME[kun]}.`;
  }
  const fid = integratorField(ma, zhi);
  return `Сегодня ${KUN_THEME[fid]}, в полную силу.`;
}

