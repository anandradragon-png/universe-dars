// Для интегратора «главное» поле — не-девятка (для 9-9-9 это 9).
function integratorField(ma, zhi) {
  if (ma !== 9) return ma;
  if (zhi !== 9) return zhi;
  return 9;
}

const EXT = fields.dars_extended || {};
const FIELD = {}; // id -> field object
fields.fields.forEach(f => { FIELD[f.id] = f; });

function reduce(n) {
  while (n > 9) n = n.toString().split('').reduce((s, d) => s + parseInt(d, 10), 0);
  return n;
}

